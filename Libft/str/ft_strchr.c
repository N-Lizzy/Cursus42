#include "libft.h"

char	*ft_strchr(const char *str, int c)
{
	unsigned int	i;
	char			cc;

	i = 0;
	cc = (char) c;
	while (str[i])
	{
		if (str[i] == cc)
			return ((char *) &str[i]);
		i++;
	}
	if (str[i] == cc)
		return ((char *) &str[i]);
	return (NULL);
}
